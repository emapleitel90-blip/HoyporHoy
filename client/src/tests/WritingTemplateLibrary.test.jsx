it('admite nombres heredados de JavaScript y exige sus valores sin interpretar el contenido',async()=>{
    const content='{{constructor}} / {{toString}} / {{__proto__}} / {{hasOwnProperty}} / {{constructor}}';
    const model={id:'special',title:'Campos especiales',content,jurisdiction:'Demo',fuero:'Demo',kind:'Demo'};
    axios.get.mockResolvedValue({data:[model]});const onUse=vi.fn();
    render(<WritingTemplateLibrary caseId="case" canManage={false} onUse={onUse}/>);
    fireEvent.click(screen.getByRole('button',{name:'Biblioteca de modelos del estudio'}));
    fireEvent.click(await screen.findByRole('button',{name:'Preparar escrito desde Campos especiales'}));
    const use=screen.getByRole('button',{name:'Abrir como nuevo escrito'});
    expect(use.disabled).toBe(true);
    for(const field of ['constructor','toString','__proto__','hasOwnProperty']) {
        expect(screen.getByLabelText('Valor para '+field).value).toBe('');
        fireEvent.change(screen.getByLabelText('Valor para '+field),{target:{value:field==='constructor'?'$& {{literal}}':field}});
    }
    expect(use.disabled).toBe(false);
    fireEvent.click(use);
    expect(onUse).toHaveBeenCalledWith({title:model.title,content:'$& {{literal}} / toString / __proto__ / hasOwnProperty / $& {{literal}}'});
    expect(model.content).toBe(content);
    // Reabrir el modelo debe descartar los valores de la preparación anterior.
    fireEvent.click(screen.getByRole('button',{name:'Preparar escrito desde Campos especiales'}));
    expect(screen.getByLabelText('Valor para __proto__').value).toBe('');
    expect(use.disabled).toBe(true);
    expect(axios.post).not.toHaveBeenCalled();
});
